"""Generate public CMS fixtures with an independent OpenSSL 4.1+ executable."""

import argparse
from pathlib import Path
import subprocess
import tempfile


ALGORITHMS = [
    "ML-DSA-44", "ML-DSA-65", "ML-DSA-87",
    "SLH-DSA-SHA2-128f", "SLH-DSA-SHAKE-128f",
]
MESSAGE = b"UEFI CMS provider regression\0"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--openssl", required=True, type=Path)
    args = parser.parse_args()
    openssl = args.openssl.resolve()
    header = [
        "/** @file",
        "  Public test fixtures generated by GenerateFixtures.py.",
        "",
        "  Copyright (c) Microsoft Corporation.",
        "  SPDX-License-Identifier: BSD-2-Clause-Patent",
        "**/",
        "",
    ]

    def array(name, data):
        header.append(f"STATIC CONST UINT8  {name}[] = {{")
        for offset in range(0, len(data), 12):
            header.append("  " + ", ".join(
                f"0x{value:02X}" for value in data[offset:offset + 12]
            ) + ",")
        header.extend(["};", ""])

    with tempfile.TemporaryDirectory(prefix="uefi-pqc-fixtures-") as directory:
        work = Path(directory)
        (work / "message.bin").write_bytes(MESSAGE)
        (work / "openssl.cnf").write_text("[req]\ndistinguished_name=dn\n[dn]\n")

        def run(*command):
            subprocess.run([str(openssl), *command], cwd=work, check=True)

        for index, name in enumerate(ALGORITHMS + ["RSA"]):
            key_options = ["-pkeyopt", "rsa_keygen_bits:2048"] if name == "RSA" else []
            run("genpkey", "-algorithm", name, *key_options, "-out", "key.pem")
            run("req", "-new", "-x509", "-key", "key.pem", "-config", "openssl.cnf",
                "-subj", "/CN=UEFI-PQC-Test", "-days", "3650", "-out", "cert.pem")
            run("x509", "-in", "cert.pem", "-outform", "DER", "-out", "cert.der")
            if name == "RSA":
                array("mUntrustedCertificate", (work / "cert.der").read_bytes())
                continue
            run("cms", "-sign", "-binary", "-in", "message.bin", "-signer", "cert.pem",
                "-inkey", "key.pem", "-outform", "DER", "-out", "cms.der")
            array(f"mCertificate{index}", (work / "cert.der").read_bytes())
            array(f"mCms{index}", (work / "cms.der").read_bytes())

    header.extend([
        "typedef struct {",
        "  CONST UINT8  *Certificate;",
        "  UINTN        CertificateSize;",
        "  CONST UINT8  *Cms;",
        "  UINTN        CmsSize;",
        "} CMS_FIXTURE;",
        "",
        "STATIC CMS_FIXTURE  mCmsFixtures[] = {",
    ])
    for index in range(len(ALGORITHMS)):
        header.append(
            f"  {{ mCertificate{index}, sizeof (mCertificate{index}), "
            f"mCms{index}, sizeof (mCms{index}) }},"
        )
    header.extend(["};", ""])
    Path(__file__).with_name("PqcFixtures.h").write_bytes(
        "\r\n".join(header).encode("ascii")
    )


if __name__ == "__main__":
    main()
